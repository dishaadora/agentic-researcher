import Link from "next/link";
import { DifficultyMark } from "@/components/badges";
import { SubmitForm } from "@/components/submit-form";
import { CATALOG, catalogCounts, catalogStatus } from "@/lib/catalog";
import { listGuides } from "@/lib/store";
import { formatDifficultyRange, formatHours, scoreGuide } from "@/lib/score";

export const dynamic = "force-dynamic";

const STATUS_TEXT = { managed: "Composio-managed app available", byo: "Your own app required", not_listed: "Not in Composio's directory" };

export default function Home() {
  const guides = listGuides();
  const names = CATALOG.entries.map((entry) => entry.name);
  return (
    <>
      <section className="hero">
        <h1>Will your OAuth app take an hour, or months?</h1>
        <p className="lede">
          Look up an app to see the real path to approval: how long it takes, what could block you, and which parts an agent can do for you.
        </p>
        <SubmitForm names={names} />
      </section>

      <section aria-labelledby="library">
        <div className="section-head">
          <h2 id="library">Guides so far</h2>
          <p className="muted">
            {guides.length} guides. Composio's directory lists {catalogCounts.total} OAuth toolkits: {catalogCounts.managed} with a managed app and {catalogCounts.byo} where you bring your own.
          </p>
        </div>
        <ul className="cards">
          {guides.map((guide) => {
            const range = scoreGuide(guide);
            const first = guide.paths[0];
            return (
              <li key={guide.slug}>
                <Link href={`/guides/${guide.slug}`} className="card">
                  <div className="card-top">
                    <h3>{guide.name}</h3>
                    <span className="muted small">{guide.category}</span>
                  </div>
                  <p className="card-rating">
                    <DifficultyMark level={range.to} /> {formatDifficultyRange(range)}
                  </p>
                  <p className="card-summary">{guide.summary}</p>
                  <dl className="card-facts">
                    <div>
                      <dt>Fastest start</dt>
                      <dd>{first ? formatHours(first.handsOnHours) : "No path found"}</dd>
                    </div>
                    <div>
                      <dt>Routes</dt>
                      <dd>{guide.paths.length}</dd>
                    </div>
                  </dl>
                  <p className="small muted">{STATUS_TEXT[catalogStatus(guide.name)]}</p>
                  {guide.origin === "live_agent" ? <p className="small tag-live">Generated by agent</p> : null}
                </Link>
              </li>
            );
          })}
        </ul>
      </section>
    </>
  );
}
